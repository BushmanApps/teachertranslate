import { useState, useEffect } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { base44 } from "@/api/base44Client";
import { Loader2, ArrowRight, Copy, Check, Share2, Mail, X } from "lucide-react";

const APP_URL = "https://teacher-translate.base44.app";
const APP_PROMO = `\n\n✍️ Write back to teachers in perfect teacher-speak with Teacher Translate.\nTry it free: ${APP_URL}`;

export default function TeacherTalkTranslator({ studentYear, studentName, isBrutalMode, mode, onResetMode }) {
  const isBrutal = false;
  const [input, setInput] = useState("");
  const [results, setResults] = useState({}); // { honest_helpful: {...}, hilarious: {...} }
  const [loading, setLoading] = useState(false);
  const [copied, setCopied] = useState(false);
  const [shareOpen, setShareOpen] = useState(false);
  const [showWarning, setShowWarning] = useState(isBrutalMode);

  const result = results[mode] || null;

  const handleTranslate = async () => {
    const text = input.trim();
    if (!text) return;
    setLoading(true);
    setResults({});
    try {
      // Preload both modes in parallel so switching is seamless
      const [honestRes, hilariousRes] = await Promise.all([
        base44.functions.invoke("translateToTeacherTalk", {
          plainText: text, studentYear, studentName, mode: "honest_helpful"
        }),
        base44.functions.invoke("translateToTeacherTalk", {
          plainText: text, studentYear, studentName, mode: "hilarious"
        })
      ]);
      const next = {};
      if (honestRes.data?.result) next.honest_helpful = honestRes.data.result;
      if (hilariousRes.data?.result) next.hilarious = hilariousRes.data.result;
      setResults(next);
    } catch (e) {
      console.error(e);
    } finally {
      setLoading(false);
    }
  };

  const handleCopy = () => {
    if (result?.teacher_talk) {
      navigator.clipboard.writeText(result.teacher_talk);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const getShareText = () =>
  `✍️ Teacher-speak translation:\n\n"${result?.teacher_talk}"\n\nGenerated by Teacher Translate${APP_PROMO}`;

  const handleShareNative = async () => {
    try {
      await navigator.share({ title: "Teacher Translate", text: getShareText() });
    } catch (e) {
      if (e.name !== 'AbortError') {
        await navigator.clipboard.writeText(getShareText());
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      }
    }
  };

  const handleShareCopy = async () => {
    await navigator.clipboard.writeText(getShareText());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleShareEmail = () => {
    const subject = encodeURIComponent("Teacher-speak translation");
    const body = encodeURIComponent(getShareText());
    window.open(`mailto:?subject=${subject}&body=${body}`);
  };

  const canNativeShare = typeof navigator !== "undefined" && !!navigator.share;

  useEffect(() => {
    setShowWarning(isBrutalMode);
  }, [isBrutalMode]);

  return (
    <div className="space-y-4">
      <AnimatePresence>
        {showWarning &&
        <>
            <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="fixed inset-0 z-50 bg-black/60 flex items-center justify-center px-6" />
          
            <motion.div
            initial={{ opacity: 0, scale: 0.92, y: 20 }}
            animate={{ opacity: 1, scale: 1, y: 0 }}
            exit={{ opacity: 0, scale: 0.92, y: 20 }}
            className="fixed inset-0 z-50 flex items-center justify-center px-6 pointer-events-none">
            
              <div className="bg-white rounded-3xl shadow-2xl p-6 max-w-sm w-full pointer-events-auto space-y-4 text-center">
                <div className="text-5xl">🍎</div>
                <h2 className="font-fredoka text-xl text-primary">Steady on.</h2>
                <p className="leading-relaxed bg-[#ffe785] text-[#4c4c9a] text-base">Teachers already cop enough. The Brutal mode for writing back is switched off — because they didn't sign up for that.

              </p>
                <p className="text-sm leading-relaxed text-[#5d5d92]">They're human too. They stay up late planning and marking, they remember your kid's name, and they genuinely care more than the report might suggest. 💛

              </p>
                <p className="text-xs text-muted-foreground italic">
                  (Also a friendly reminder: end-of-year gift season is coming. A heartfelt card goes a long way. Just saying.)
                </p>
                <button
                  onClick={() => { setShowWarning(false); onResetMode?.(); }}
                  className="w-full py-3 bg-primary text-primary-foreground font-bold rounded-2xl text-sm hover:bg-primary/90 transition-all">

                  Got it — I'll be kind 😊
                </button>
              </div>
            </motion.div>
          </>
        }
      </AnimatePresence>
      <div className={`rounded-2xl p-4 space-y-1 ${
      isBrutal ? "bg-yellow-400/20 border border-yellow-500" : "bg-purple-50 border border-purple-100"}`
      }>
        <p className="text-xs font-bold text-purple-700">💎 Paid Feature</p>
        <p className="text-xs text-muted-foreground">
          Want to write back to the teacher? Type what you actually want to say and we'll translate it into perfect teacher-speak!
        </p>
      </div>

      <div className="space-y-2">
        <label className="text-sm font-bold">What do you want to say? (Plain English)</label>
        <textarea
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder={`e.g. ${studentName || "My child"} needs to stop lying about eating all of their lunch...`}
          rows={4}
          className={`w-full rounded-xl border px-4 py-3 text-sm resize-none focus:outline-none focus:ring-2 focus:ring-ring ${
          isBrutal ? "bg-zinc-800 border-zinc-600 text-white placeholder:text-zinc-500" : "bg-background border-input"}`
          } />
        
      </div>

      <button
        onClick={handleTranslate}
        disabled={!input.trim() || loading}
        className={`w-full py-3 rounded-2xl font-bold text-sm flex items-center justify-center gap-2 transition-all disabled:opacity-40 ${
        isBrutal ?
        "bg-orange-600 hover:bg-orange-700 text-white" :
        "bg-primary hover:bg-primary/90 text-primary-foreground"}`
        }>
        
        {loading ?
        <><Loader2 className="w-4 h-4 animate-spin" /> Translating...</> :

        <>Translate to Teacher Talk <ArrowRight className="w-4 h-4" /></>
        }
      </button>

      {result &&
      <motion.div
        initial={{ opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        className={`rounded-2xl p-4 space-y-3 ${
        isBrutal ? "bg-zinc-800 border border-zinc-700" : "bg-white border border-border shadow-sm"}`
        }>
        
          <div className="flex items-center justify-between">
            <h3 className={`font-bold text-sm ${isBrutal ? "text-orange-400" : "text-primary"}`}>
              Teacher-Speak Version 📝
            </h3>
            <div className="flex items-center gap-2">
              <button
              onClick={handleCopy}
              className={`flex items-center gap-1 text-xs font-semibold px-2 py-1 rounded-lg transition-all ${
              isBrutal ? "bg-zinc-700 text-zinc-300 hover:bg-zinc-600" : "bg-muted text-muted-foreground hover:bg-border"}`
              }>
              
                {copied ? <><Check className="w-3 h-3" /> Copied!</> : <><Copy className="w-3 h-3" /> Copy</>}
              </button>
              <div className="relative">
                <button
                onClick={() => setShareOpen(!shareOpen)}
                className={`flex items-center gap-1 text-xs font-semibold px-2 py-1 rounded-lg transition-all ${
                isBrutal ? "bg-orange-700 text-white hover:bg-orange-600" : "bg-primary/10 text-primary hover:bg-primary/20"}`
                }>
                
                  <Share2 className="w-3 h-3" /> Share
                </button>
                <AnimatePresence>
                  {shareOpen &&
                <>
                      <motion.div
                    initial={{ opacity: 0 }}
                    animate={{ opacity: 1 }}
                    exit={{ opacity: 0 }}
                    className="fixed inset-0 z-40"
                    onClick={() => setShareOpen(false)} />
                  
                      <motion.div
                    initial={{ opacity: 0, scale: 0.95, y: 8 }}
                    animate={{ opacity: 1, scale: 1, y: 0 }}
                    exit={{ opacity: 0, scale: 0.95, y: 8 }}
                    className={`absolute right-0 bottom-8 z-50 w-56 rounded-2xl shadow-xl border p-2 space-y-1 ${
                    isBrutal ? "bg-zinc-900 border-zinc-700" : "bg-white border-border"}`
                    }>
                    
                        <div className="flex items-center justify-between px-2 py-1 mb-1">
                          <span className={`text-xs font-bold uppercase tracking-wide ${isBrutal ? "text-zinc-400" : "text-muted-foreground"}`}>Share</span>
                          <button onClick={() => setShareOpen(false)}><X className="w-3.5 h-3.5 text-muted-foreground" /></button>
                        </div>
                        {canNativeShare &&
                    <button onClick={handleShareNative} className={`flex items-center gap-2 w-full px-3 py-2 rounded-xl text-sm font-semibold text-left transition-all ${isBrutal ? "bg-zinc-800 hover:bg-zinc-700 text-zinc-100" : "bg-muted hover:bg-border text-foreground"}`}>
                            <Share2 className="w-4 h-4 shrink-0" /> Share via…
                          </button>
                    }
                        <button onClick={handleShareEmail} className={`flex items-center gap-2 w-full px-3 py-2 rounded-xl text-sm font-semibold text-left transition-all ${isBrutal ? "bg-zinc-800 hover:bg-zinc-700 text-zinc-100" : "bg-muted hover:bg-border text-foreground"}`}>
                          <Mail className="w-4 h-4 shrink-0" /> Email
                        </button>
                        <button onClick={handleShareCopy} className={`flex items-center gap-2 w-full px-3 py-2 rounded-xl text-sm font-semibold text-left transition-all ${isBrutal ? "bg-zinc-800 hover:bg-zinc-700 text-zinc-100" : "bg-muted hover:bg-border text-foreground"}`}>
                          {copied ? <Check className="w-4 h-4 shrink-0 text-green-500" /> : <Copy className="w-4 h-4 shrink-0" />}
                          {copied ? "Copied!" : "Copy text"}
                        </button>
                      </motion.div>
                    </>
                }
                </AnimatePresence>
              </div>
            </div>
          </div>

          <p className={`text-sm leading-relaxed font-medium italic ${isBrutal ? "text-zinc-100" : "text-foreground"}`}>
            "{result.teacher_talk}"
          </p>

          {result.translation_notes &&
        <div className={`text-xs rounded-lg p-2 ${
        isBrutal ? "bg-orange-950/40 text-orange-300" : "bg-amber-50 text-amber-800"}`
        }>
              <strong>What this means:</strong> {result.translation_notes}
            </div>
        }
        </motion.div>
      }
    </div>);

}